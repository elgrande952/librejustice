-- Sonde par namespace sur `entity.uid` : btree `text_pattern_ops`.
--
-- Les passes de liaison des parties scopées au lot (at-write) qui
-- visent les avocats aux Conseils attaquent le registre par son namespace :
-- `WHERE e.uid LIKE 'oacc:%'` / `'oacc:firm-%'`. `entity_pkey` est un btree en
-- collation par défaut : inutilisable pour un `LIKE 'préfixe%'`. Postgres
-- seq-scannait donc les 29 M lignes (12 Go) d'`entity` pour en ramener 57 —
-- 3,3 s par lot, mesurées à 85 % du temps d'horloge d'un ingest nocturne
-- (61 358 s cumulées sur 18 499 appels, pour 9 393 lignes liées).
--
-- Le commentaire de `parties.rs` supposait le coût trivial parce que le
-- registre est minuscule (~140 entrées) : le dépliage l'est, le *trouver* ne
-- l'était pas.
--
-- `text_pattern_ops` plutôt qu'un index partiel `WHERE uid LIKE 'oacc:%'` :
-- Postgres ne prouve pas l'implication entre deux `LIKE`, donc un partiel sur
-- `'oacc:%'` sert `oacc:%` mais PAS `oacc:firm-%` (vérifié : 0,26 ms contre
-- 8,2 s). L'index complet sert tous les namespaces (`siren:`, `rna:`, `cnb:`,
-- `oacc:`) uniformément.
--
-- Mesuré sur la prod : construction 18 s, 879 Mo, sonde 3 680 ms → 0,37 ms.
CREATE INDEX IF NOT EXISTS entity_uid_pattern_idx ON entity (uid text_pattern_ops);
