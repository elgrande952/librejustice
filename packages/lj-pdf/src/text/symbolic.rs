/// The built-in encoding of the standard Symbol font.
pub(super) fn symbol_char(byte: u8) -> Option<char> {
    let unit: u32 = match byte {
        0x20 | 0x21 | 0x23 | 0x25 | 0x26 | 0x28 | 0x29 | 0x2B | 0x2C | 0x2E..=0x3F => {
            u32::from(byte)
        }
        0x5B | 0x5D | 0x5F | 0x7B..=0x7D => u32::from(byte),
        0x22 => 0x2200,
        0x24 => 0x2203,
        0x27 => 0x220B,
        0x2A => 0x2217,
        0x2D => 0x2212,
        0x40 => 0x2245,
        0x41..=0x5A => GREEK_UPPER[usize::from(byte - 0x41)],
        0x5C => 0x2234,
        0x5E => 0x22A5,
        0x61..=0x7A => GREEK_LOWER[usize::from(byte - 0x61)],
        0x7E => 0x223C,
        0xA0..=0xE5 => HIGH[usize::from(byte - 0xA0)],
        0xF1 => 0x232A,
        0xF2 => 0x222B,
        0xF3 => 0x2320,
        0xF5 => 0x2321,
        _ => return None,
    };
    char::from_u32(unit).filter(|c| *c != '\0')
}

