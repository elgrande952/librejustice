/// The built-in encoding of ZapfDingbats, which the Unicode Dingbats block follows.
pub(super) fn dingbats_char(byte: u8) -> Option<char> {
    let unit: u32 = match byte {
        0x20 => 0x20,
        0x21..=0x24 => 0x2701 + u32::from(byte - 0x21),
        0x25 => 0x260E,
        0x26..=0x29 => 0x2706 + u32::from(byte - 0x26),
        0x2A => 0x261B,
        0x2B => 0x261E,
        0x2C..=0x47 => 0x270C + u32::from(byte - 0x2C),
        0x48 => 0x2605,
        0x49..=0x6B => 0x2729 + u32::from(byte - 0x49),
        0x6C => 0x25CF,
        0x6D => 0x274D,
        0x6E => 0x25A0,
        0x6F..=0x72 => 0x274F + u32::from(byte - 0x6F),
        0x73 => 0x25B2,
        0x74 => 0x25BC,
        0x75 => 0x25C6,
        0x76 => 0x2756,
        0x77 => 0x25D7,
        0x78..=0x7E => 0x2758 + u32::from(byte - 0x78),
        0x80..=0x8D => 0x2768 + u32::from(byte - 0x80),
        0xA1..=0xA7 => 0x2761 + u32::from(byte - 0xA1),
        0xA8 => 0x2663,
        0xA9 => 0x2666,
        0xAA => 0x2665,
        0xAB => 0x2660,
        0xAC..=0xB5 => 0x2460 + u32::from(byte - 0xAC),
        0xB6..=0xD3 => 0x2776 + u32::from(byte - 0xB6),
        0xD4 => 0x2794,
        0xD5 => 0x2192,
        0xD6 => 0x2194,
        0xD7 => 0x2195,
        0xD8..=0xEF => 0x2798 + u32::from(byte - 0xD8),
        0xF1..=0xFE => 0x27B1 + u32::from(byte - 0xF1),
        _ => return None,
    };
    char::from_u32(unit)
}

#[cfg(test)]
mod tests {
    use super::{dingbats_char, symbol_char};

    #[test]
    fn symbol_and_dingbats_read_their_own_encodings() {
        let symbol: String = [0x61, 0x57, 0xB7, 0xD3, 0x2D, 0x31]
            .into_iter()
            .filter_map(symbol_char)
            .collect();
        assert_eq!(symbol, "\u{3b1}\u{3a9}\u{2022}\u{a9}\u{2212}1");
        let dingbats: String = [0x21, 0x48, 0x6C, 0xAC, 0xD4, 0xFE]
            .into_iter()
            .filter_map(dingbats_char)
            .collect();
        assert_eq!(dingbats, "\u{2701}\u{2605}\u{25cf}\u{2460}\u{2794}\u{27be}");
        assert_eq!(symbol_char(0xBD), None);
    }
}
